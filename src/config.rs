/// Where the narrator voice (`cache/voice_reference.wav`) comes from.
/// - "file": a recording chosen by the user (`VOICE_REFERENCE_FILE`)
/// - "design": generated from `NARRATOR_PROMPT` by the VoiceDesign model
/// - "random": generated by the Base model itself (voice depends on `VOICE_SEED`)
pub const VOICE_SOURCE_CHOICES: &[&str] = &["file", "design", "random"];

/// The only Qwen3-TTS checkpoint that turns a description into a voice.
pub const DEFAULT_VOICE_DESIGN_MODEL: &str = "Qwen/Qwen3-TTS-12Hz-1.7B-VoiceDesign";

pub const DEFAULT_NARRATOR_PROMPT: &str = "A calm, clear and warm narrator voice. \
Speaks at a measured, unhurried pace with natural intonation, \
like an experienced audiobook reader presenting a non-fiction text.";

/// GUI label for a TTS model id (the id itself if it is not a known choice).
pub fn tts_model_label(model_id: &str) -> String {
    TTS_MODEL_CHOICES
        .iter()
        .find(|(_, id)| *id == model_id)
        .map(|(label, _)| label.to_string())
        .unwrap_or_else(|| model_id.to_string())
}

/// TTS model id for a GUI label (labels that are not known pass through).
pub fn tts_model_id(label: &str) -> String {
    TTS_MODEL_CHOICES
        .iter()
        .find(|(l, _)| *l == label)
        .map(|(_, id)| id.to_string())
        .unwrap_or_else(|| label.to_string())
}

/// Loudness of the finished audiobook: -16 LUFS is the usual level for
/// spoken word on phones and in podcast apps.
pub const DEFAULT_LOUDNESS_TARGET_LUFS: i32 = -16;

/// All user-adjustable settings. Field names map to the upper-case keys of
/// `settings.json` (`MAX_WORDS_PER_CHUNK`, `TTS_LANGUAGE`, ...).
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "SCREAMING_SNAKE_CASE")]
pub struct Settings {
    pub max_words_per_chunk: usize,
    pub voice_seed: u64,
    pub sample_rate: u32,
    pub crossfade_ms: u32,
    pub silence_after_period_ms: u32,
    pub silence_after_paragraph_ms: u32,
    /// Integrated loudness of the finished MP3/WAV in LUFS (EBU R128);
    /// peaks are limited to -1.5 dBFS. 0 (or above) leaves the level as
    /// synthesized.
    pub loudness_target_lufs: i32,
    pub llm_max_retries: u32,
    pub log_level_console: String,
    pub log_level_file: String,
    pub narrator_prompt: String,
    pub storage_backend: String,
    pub tts_max_tokens: usize,
    pub tts_max_words_fallback: usize,
    pub chapter_by_chapter: bool,
    pub vocalize_chapter_names: bool,
    /// Language passed to Qwen3-TTS for every segment. "auto" uses the
    /// per-segment language detected by the LLM. A fixed language avoids
    /// mispronunciation when the small LLM mislabels a chunk and skips the
    /// ten language probes in stage 1.
    pub tts_language: String,
    /// Precision for the TTS model on the GPU: "bfloat16" (falls back to
    /// float16 on GPUs without bf16 support), "float16" or "float32".
    pub tts_dtype: String,
    /// Layers of the Llama helper model offloaded to the GPU: 0 = CPU only
    /// (keeps VRAM free for TTS on small GPUs), -1 = all layers.
    pub llm_gpu_layers: i32,
    pub tts_model_name: String,
    /// Use the Llama helper model in stage 1 (emotion spans, story and
    /// chapter titles, reading order of files, language detection for
    /// `TTS_LANGUAGE = "auto"`). Off: rules only (file names, headings).
    pub use_llm: bool,
    /// Spell out numbers, dates, times, units and common abbreviations
    /// before synthesis (German texts only).
    pub normalize_numbers: bool,
    /// Guided review of the spots the number rules cannot decide (ordinals
    /// without clear context, Roman numerals); needs `NORMALIZE_NUMBERS`.
    pub review_numbers: bool,
    /// After synthesis, audit every chunk (speech share, volume, clipping,
    /// voice match), delete failed ones and synthesize them again with a
    /// different seed.
    pub auto_cleanup: bool,
    /// Source of the narrator voice, see [`VOICE_SOURCE_CHOICES`].
    pub voice_source: String,
    /// Recording used with `VOICE_SOURCE = "file"` (WAV, 10–15 s).
    pub voice_reference_file: String,
    /// Model for `VOICE_SOURCE = "design"`.
    pub voice_design_model: String,
    /// Runtime only (not stored): run without models; the LLM answers with
    /// neutral defaults and the TTS writes silence. For tests and dry runs.
    #[serde(skip)]
    pub mock_models: bool,
}

